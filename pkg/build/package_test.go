func Test_removeSelfProvidedDeps_WithVersionedProvides(t *testing.T) {
	provides := []string{"so:libfoo.so.3=3", "so:libbar.so.2=2"}
	depends := []string{"so:libbaz.so.4", "so:libfoo.so.3"}

	final := removeSelfProvidedDeps(depends, provides)

	require.Equal(t, len(final), 1, "only one depend in the list")
	require.Equal(t, final[0], "so:libbaz.so.4", "remaining depend should be so:libbaz.so.4")
}

func Test_removeSelfProvidedDeps_WithoutVersionedProvides(t *testing.T) {
	provides := []string{"so:libfoo.so.3", "so:libbar.so.2"}
	depends := []string{"so:libbaz.so.4", "so:libfoo.so.3"}

	final := removeSelfProvidedDeps(depends, provides)

	require.Equal(t, len(final), 1, "only one depend in the list")
	require.Equal(t, final[0], "so:libbaz.so.4", "remaining depend should be so:libbaz.so.4")
}

func Test_removeSelfProvidedDeps_WithEmptyProvides(t *testing.T) {
	provides := []string{}
	depends := []string{"so:libbaz.so.4", "so:libfoo.so.3"}

	final := removeSelfProvidedDeps(depends, provides)

	require.Equal(t, len(final), 2, "only two depends in the list")
	require.Equal(t, final[0], "so:libbaz.so.4", "first remaining depend should be so:libbaz.so.4")
	require.Equal(t, final[1], "so:libfoo.so.3", "second remaining depend should be so:libfoo.so.3")
}

func Test_GenerateControlData(t *testing.T) {
	pkg := &config.Package{
		Version: "1.2.3",
		Epoch:   4,
	}

	tests := []struct {
		name string
		pb   *PackageBuild
		want string
	}{{
		name: "simple",
		pb: &PackageBuild{
			Build: &Build{
				SourceDateEpoch: time.Unix(0, 0),
				Namespace:       "wolfi",
			},
			Origin:        pkg,
			PackageName:   "glibc",
			Arch:          "aarch64",
			InstalledSize: 666,
			OriginName:    "bigbang",
			Description:   "I'm a unit test",
			URL:           "https://chainguard.dev",
			Commit:        "deadbeef",
			DataHash:      "baadf00d",
		},
		want: `# Generated by melange
pkgname = glibc
pkgver = 1.2.3-r4
arch = aarch64
size = 666
origin = bigbang
pkgdesc = I'm a unit test
url = https://chainguard.dev
commit = deadbeef
maintainer = wolfi
datahash = baadf00d
`,
	}, {
		name: "source date epoch",
		pb: &PackageBuild{
			Build: &Build{
				SourceDateEpoch: time.Unix(12345678, 0),
			},
			Origin:        pkg,
			PackageName:   "glibc",
			Arch:          "aarch64",
			InstalledSize: 666,
			OriginName:    "bigbang",
			Description:   "I'm a unit test",
			URL:           "https://chainguard.dev",
			Commit:        "deadbeef",
			DataHash:      "baadf00d",
		},
		want: `# Generated by melange
pkgname = glibc
pkgver = 1.2.3-r4
arch = aarch64
size = 666
origin = bigbang
pkgdesc = I'm a unit test
url = https://chainguard.dev
commit = deadbeef
builddate = 12345678
datahash = baadf00d
`,
	}}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			gotBuf := bytes.NewBuffer(nil)
			err := test.pb.GenerateControlData(gotBuf)
			if err != nil {
				t.Fatalf("GenerateControlData() = %v", err)
			}
			got := gotBuf.String()
			if test.want != got {
				t.Errorf("GenerateControlData() = %s, wanted %s", got, test.want)
			}
		})
	}
}

// hardlinkPackage lays out a package with usr/bin/tool hard linked as
// usr/bin/alias and usr/lib/tool, next to an unrelated usr/lib/other, and
// returns the filesystem EmitPackage reads it through.
func hardlinkPackage(t *testing.T) (*PackageBuild, apkofs.FullFS) {
	t.Helper()
	pc := &PackageBuild{
		Build: &Build{
			SourceDateEpoch: time.Unix(0, 0),
			WorkspaceDir:    t.TempDir(),
		},
		PackageName: "hardlinks",
	}
	dir := pc.WorkspaceSubdir()
	for _, d := range []string{"usr/bin", "usr/lib"} {
		if err := os.MkdirAll(filepath.Join(dir, d), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	tool := filepath.Join(dir, "usr/bin/tool")
	if err := os.WriteFile(tool, []byte("tool contents"), 0o755); err != nil {
		t.Fatal(err)
	}
	for _, l := range []string{"usr/bin/alias", "usr/lib/tool"} {
		if err := os.Link(tool, filepath.Join(dir, l)); err != nil {
			t.Fatal(err)
		}
	}
	other := filepath.Join(dir, "usr/lib/other")
	if err := os.WriteFile(other, []byte("other contents"), 0o644); err != nil {
		t.Fatal(err)
	}

	fsys, err := apkofs.Sub(
		apkofs.DirFS(t.Context(), pc.Build.WorkspaceDir),
		filepath.Join(melangeOutputDirName, pc.PackageName),
	)
	if err != nil {
		t.Fatal(err)
	}
	return pc, fsys
}

// A file with several hard links is installed once, so it counts once.
func Test_calculateInstalledSize_Hardlinks(t *testing.T) {
	pc, fsys := hardlinkPackage(t)

	want := int64(len("tool contents") + len("other contents"))
	for _, d := range []string{".", "usr", "usr/bin", "usr/lib"} {
		fi, err := os.Lstat(filepath.Join(pc.WorkspaceSubdir(), d))
		if err != nil {
			t.Fatal(err)
		}
		want += fi.Size()
	}

	if err := pc.calculateInstalledSize(fsys); err != nil {
		t.Fatal(err)
	}
	if pc.InstalledSize != want {
		t.Errorf("installed size %d, want %d", pc.InstalledSize, want)
	}
}

// Files hard linked in the workspace are written once, with every other path
// to the same inode as a link to the first one in walk order.
func Test_emitDataSection_Hardlinks(t *testing.T) {
	pc, fsys := hardlinkPackage(t)

	out, err := os.Create(filepath.Join(t.TempDir(), "data.tar.gz"))
	if err != nil {
		t.Fatal(err)
	}
	defer out.Close()
	if err := pc.emitDataSection(t.Context(), fsys, fsys, nil, nil, out); err != nil {
		t.Fatal(err)
	}

	zr, err := gzip.NewReader(out)
	if err != nil {
		t.Fatal(err)
	}
	tr := tar.NewReader(zr)
	got := map[string]*tar.Header{}
	contents := map[string]string{}
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			t.Fatal(err)
		}
		body, err := io.ReadAll(tr)
		if err != nil {
			t.Fatal(err)
		}
		got[hdr.Name] = hdr
		contents[hdr.Name] = string(body)
	}

	// usr/bin/alias sorts first, so it carries the contents
	regular := map[string]string{
		"usr/bin/alias": "tool contents",
		"usr/lib/other": "other contents",
	}
	for name, want := range regular {
		hdr, ok := got[name]
		if !ok {
			t.Fatalf("%s: missing", name)
		}
		if hdr.Typeflag != tar.TypeReg {
			t.Errorf("%s: type %q, want regular file", name, hdr.Typeflag)
		}
		if contents[name] != want {
			t.Errorf("%s: contents %q, want %q", name, contents[name], want)
		}
	}
	for _, name := range []string{"usr/bin/tool", "usr/lib/tool"} {
		hdr, ok := got[name]
		if !ok {
			t.Fatalf("%s: missing", name)
		}
		if hdr.Typeflag != tar.TypeLink || hdr.Linkname != "usr/bin/alias" || hdr.Size != 0 {
			t.Errorf("%s: type %q linkname %q size %d, want a link to usr/bin/alias with size 0",
				name, hdr.Typeflag, hdr.Linkname, hdr.Size)
		}
	}
}
